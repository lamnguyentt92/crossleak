def utility_numbers(M: Macros, main: dict, v3: dict, v4: dict, snaive: dict, fallback: dict, out: Path) -> None:
    U3, U2, U4 = v3["utility"], main["utility"], v4["utility"]
    g = lambda U, ds, mod, ell, c: U[ds][mod][str(ell)]["configs"][c]["gain"]  # noqa: E731
    # ranges of the one-day cross-learning gain over the three utility campaigns
    eld_xl = [g(U, "eld", "c2base", 24, c)["est"] for U in (U2, U3, U4) for c in U["eld"]["c2base"]["24"]["configs"] if c.startswith("xl")]
    ls_xl = [g(U, "lifesnaps", m, 24, c)["est"] for U in (U2, U3, U4) for m in ("c2base", "c2small")
             for c in U["lifesnaps"][m]["24"]["configs"] if c.startswith("xl")]
    M.put("EldXlRange", rng(eld_xl), "xl gains, eld c2base, l=24, v0.2+v0.3+v0.4")
    M.put("LsXlRange", rng(ls_xl), "xl gains, lifesnaps both models, l=24, v0.2+v0.3+v0.4")
    M.put("EldXlSixteen", cid(g(U3, "eld", "c2base", 24, "xl16")), "v3 eld c2base xl16 gain, 95% CI")
    M.put("EldDoneSixteen", cid(g(U3, "eld", "c2base", 24, "d1_16")), "v3 eld c2base d1_16 gain")
    M.put("EldDfourEpsOne", cid(g(U3, "eld", "c2base", 24, "d4_P8_eps1")), "v3 eld c2base d4 P8 eps1 gain")
    M.put("EldSmallXlRange", rng([g(U, "eld", "c2small", 24, c)["est"] for U in (U2, U3, U4) for c in U["eld"]["c2small"]["24"]["configs"] if c.startswith("xl")]),
          "xl gains, eld c2small, l=24, v0.2+v0.3+v0.4")
    M.put("EldFullGain", pct(g(U3, "eld", "c2base", 24, "full")["est"], 0), "v3 eld c2base full-history gain")
    v2d4 = U2["eld"]["c2base"]["24"]["configs"]["d4_P8_eps1"]
    M.put("MainEldDfourGain", cid(v2d4["gain"]), "v0.2 eld c2base d4 P8 eps1 gain")
    M.put("MainEldDfourRetained", cid(v2d4["retained_vs_xl16"], 1, 2), "v0.2 retained vs xl16")

    # Table 1: v0.3, one day of history
    cols = [("eld", "c2base"), ("eld", "c2small"), ("lifesnaps", "c2base"), ("lifesnaps", "c2small")]
    ref = {"eld": ("xl4", "xl16", "d1_16"), "lifesnaps": ("xl4", "xl8", "d1_4")}
    rows = []
    iso = []
    for ds, mod in cols:
        cfg = U3[ds][mod]["24"]["configs"]
        gain0 = cfg["xl4"]
        wql_iso = gain0["wql_mean"] / (1 - gain0["gain"]["est"])  # gain = 1 - WQL(config)/WQL(isolated)
        iso.append(f"{wql_iso:.3f}")
    rows.append("WQL, isolated (D0) & " + " & ".join(iso) + " \\\\ \\midrule")
    labels = [("XL, $k=4$", lambda ds: "xl4"), ("XL, $k=16$ / $k=8$", lambda ds: ref[ds][1]),
              ("D1 public, $k=16$ / $k=4$", lambda ds: ref[ds][2]), ("D4, $P=8$, $\\varepsilon=1$", lambda ds: "d4_P8_eps1"),
              ("D4, $P=8$, $\\varepsilon=4$", lambda ds: "d4_P8_eps4"), ("Full history (reference)", lambda ds: "full"),
              ("Seasonal naive$^{\\dagger}$", lambda ds: "snaive")]
    for lab, key in labels:
        cells = [cid(U3[ds][mod]["24"]["configs"][key(ds)]["gain"]) for ds, mod in cols]
        rows.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    (out / "tab_utility.tex").write_text("\n".join(rows) + "\n")

    # E1 / E2 (TOST, 90 % CI, margin 2 pp)
    eq = v3["equivalence"]
    assert abs(eq["margin"] - 0.02) < 1e-12
    names = {("eld", "d1_16", "xl16"): "EqEldDoneXl", ("eld", "d4_P8_eps1", "xl16"): "EqEldDfourXl",
             ("eld", "d4_P8_eps1", "d1_16"): "EqEldDfourDone", ("lifesnaps", "d1_4", "xl8"): "EqLsDoneXl",
             ("lifesnaps", "d4_P8_eps1", "xl8"): "EqLsDfourXl"}
    for p in eq["pairs"]:
        n = names[(p["dataset"], p["a"], p["b"])]
        M.put(n, ci(p["delta"], p["lo90"], p["hi90"], 100, 2, True), f"v3 equivalence {p['a']} vs {p['b']} ({p['verdict']})")
        M.put(n + "Verdict", p["verdict"].replace("_", " ").lower(), "v3 equivalence verdict")
    for p in eq["no_benefit"]:
        n = {"xl4": "NobenXlFour", "xl16": "NobenXlSixteen"}[p["config"]]
        M.put(n, ci(p["gain"], p["lo90"], p["hi90"], 100, 2, True), f"v3 no-benefit l=72 {p['config']} ({p['verdict']})")

    # post hoc: seasonal naive (docs/reanalysis/snaive_baseline.out)
    sv = lambda ver, ds, mod, ell, c: snaive[(ver, ds, mod, ell, c)]  # noqa: E731
    M.put("SnaiveEld", cid(g(U3, "eld", "c2base", 24, "snaive")), "v3 utility eld c2base snaive gain (as Table 1)")
    M.put("SnaiveEldMain", cid(g(U2, "eld", "c2base", 24, "snaive")), "v0.2 utility eld c2base snaive gain")
    M.put("SnaiveEldXlSixteen", cid(sv("v0.3", "eld", "c2base", 24, "xl16"), sign=True), "v0.3 xl16 - snaive")
    M.put("SnaiveEldXlFour", cid(sv("v0.3", "eld", "c2base", 24, "xl4"), sign=True), "v0.3 xl4 - snaive")
    M.put("SnaiveEldMainXlSixteen", cid(sv("v0.2", "eld", "c2base", 24, "xl16"), sign=True), "v0.2 xl16 - snaive")
    small = [v["est"] for (ver, ds, mod, ell, c), v in snaive.items()
             if ver == "v0.3" and ds == "eld" and mod == "c2small" and ell == 24 and c != "snaive_vs_iso"]
    assert all(v["hi"] < 0 for (ver, ds, mod, ell, c), v in snaive.items()
               if ver == "v0.3" and ds == "eld" and mod == "c2small" and ell == 24 and c != "snaive_vs_iso")
    M.put("SnaiveEldSmallRange", rng([-x for x in small], 100, 0), "v0.3 eld c2small: snaive minus every config (all CIs < 0)")
    ls = [v["est"] for (ver, ds, mod, ell, c), v in snaive.items() if ds == "lifesnaps" and ell == 24 and c != "snaive_vs_iso"]
    M.put("SnaiveLsRange", rng(ls, 100, 0), "lifesnaps: config minus snaive, both campaigns and models")
    M.put("SnaiveEldThree", fnum(100 * min(sv("v0.3", "eld", "c2base", 72, c)["est"] for c in ("xl4", "xl16")), 0),
          "v0.3 eld c2base l=72: xl minus snaive (smaller of k=4, 16)")
    # post hoc: D4 public-centre fallback
    for (ds, eps), v in fallback.items():
        tag = {"eld": "Eld", "lifesnaps": "Ls"}[ds] + {1: "One", 4: "Four"}[eps]
        M.put("Fallback" + tag, pct(v["share"], 0), "d4_fallback_share.out")
    M.put("FallbackEldUsers", str(fallback[("eld", 1)]["users"]), "d4_fallback_share.out")
    M.put("FallbackLsUsers", str(fallback[("lifesnaps", 1)]["users"]), "d4_fallback_share.out")


def causal_numbers(M: Macros, v3: dict, v4: dict) -> None:
    """The v0.4 causal-defence study (prereg/V4_PREREG.md): confirmatory pairs, effects of causality, gains."""
    eq = v4["equivalence"]
    assert abs(eq["margin"] - 0.02) < 1e-12 and eq["model"] == "c2base"
    names = {("eld", "d1p_16", "xl16"): "EqcEldDonepXl", ("eld", "d4_P8_eps1", "xl16"): "EqcEldDfourXl",
             ("eld", "d4_P8_eps1", "d1p_16"): "EqcEldDfourDonep", ("lifesnaps", "d1p_4", "xl8"): "EqcLsDonepXl",
             ("lifesnaps", "d4p_P8_eps1", "xl8"): "EqcLsDfourpXl"}
    assert {(p["dataset"], p["a"], p["b"]) for p in eq["pairs"]} == set(names)
    for p in eq["pairs"]:
        assert v4["verdicts"][f"EQC_{p['dataset']}_{p['a']}_vs_{p['b']}"] == p["verdict"]
        M.put(names[(p["dataset"], p["a"], p["b"])], ci(p["delta"], p["lo90"], p["hi90"], 100, 2, True),
              f"v4 equivalence {p['a']} vs {p['b']} ({p['verdict']})")
    pe = {(p["dataset"], p["a"], p["b"]): p for p in eq["pairs"]}[("eld", "d4_P8_eps1", "xl16")]
    assert pe["delta"] < 0
    M.put("EqcEldDfourXlDeficit", fnum(-100 * pe["delta"], 1), "v4 eld xl16 - d4_P8_eps1 (D4 deficit), points")
    eff = {("eld", "d1p_16", "d1_16"): "EffEldDonep", ("lifesnaps", "d1p_4", "d1_4"): "EffLsDonep",
           ("lifesnaps", "d4p_P8_eps1", "d4_P8_eps1"): "EffLsDfourp"}
